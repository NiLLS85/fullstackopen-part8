const seed = async () => {
  await mongoose.connect(process.env.MONGODB_URI)
  await Book.deleteMany({})
  await Author.deleteMany({})

  const saved = await Author.insertMany(authors.map(({ name, born }) => ({ name, born })))
  const idByName = Object.fromEntries(saved.map((a) => [a.name, a._id]))

  await Book.insertMany(books.map(({ title, published, author, genres }) => ({
    title, published, genres, author: idByName[author],
  })))

  console.log(`${saved.length} authors and ${books.length} books saved`)
  await mongoose.connection.close()
}

seed()
